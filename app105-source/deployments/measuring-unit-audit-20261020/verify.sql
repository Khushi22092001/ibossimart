DECLARE
    c INTEGER;
    n NUMBER;
    result NUMBER;
    pred VARCHAR2(4000):=IMART_REGISTER_KPIS.CREATION_TEST(50,'MINE');
    PROCEDURE check_user(p_user VARCHAR2, p_min NUMBER, p_max NUMBER) IS
    BEGIN
        c:=DBMS_SQL.OPEN_CURSOR;
        DBMS_SQL.PARSE(c,'select count(*) from measuringunit mr_source where '||pred,DBMS_SQL.NATIVE);
        DBMS_SQL.BIND_VARIABLE(c,':APP_USER',p_user);
        DBMS_SQL.DEFINE_COLUMN(c,1,result);
        n:=DBMS_SQL.EXECUTE(c);
        n:=DBMS_SQL.FETCH_ROWS(c);
        DBMS_SQL.COLUMN_VALUE(c,1,result);
        DBMS_SQL.CLOSE_CURSOR(c);
        IF result<p_min OR result>p_max THEN RAISE_APPLICATION_ERROR(-20001,'Incorrect creator identity count.'); END IF;
        DBMS_OUTPUT.PUT_LINE('Created by '||p_user||': '||result);
    END;
BEGIN
    IF INSTR(pred,'mr_creator_identity')=0 THEN RAISE_APPLICATION_ERROR(-20002,'Creator mapping absent.'); END IF;
    check_user('BOSS',4,4);
    check_user(' boss ',4,4);
    check_user('__UNMAPPED_VALIDATION_USER__',0,0);
    c:=DBMS_SQL.OPEN_CURSOR;
    DBMS_SQL.PARSE(c,'select count(*) from measuringunit mr_source where mr_source.measuringunitcode=''alb'' and '||pred,DBMS_SQL.NATIVE);
    DBMS_SQL.BIND_VARIABLE(c,':APP_USER','BOSS');
    DBMS_SQL.DEFINE_COLUMN(c,1,result);
    n:=DBMS_SQL.EXECUTE(c); n:=DBMS_SQL.FETCH_ROWS(c); DBMS_SQL.COLUMN_VALUE(c,1,result); DBMS_SQL.CLOSE_CURSOR(c);
    IF result<>1 THEN RAISE_APPLICATION_ERROR(-20003,'alb missing from Created by me.'); END IF;
    DBMS_OUTPUT.PUT_LINE('alb is included in Created by me.');
END;
