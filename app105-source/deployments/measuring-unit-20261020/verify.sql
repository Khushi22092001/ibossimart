DECLARE
    l_tno MEASURINGUNIT.TNO%TYPE;
    PROCEDURE reject_value(p_value NUMBER) IS
        l_rejected BOOLEAN := FALSE;
    BEGIN
        SAVEPOINT value_test;
        BEGIN
            UPDATE MEASURINGUNIT SET DECIMALPLACE=p_value WHERE TNO=l_tno;
        EXCEPTION WHEN OTHERS THEN
            IF SQLCODE IN (-1407,-2290) THEN
                l_rejected := TRUE;
            ELSE
                RAISE;
            END IF;
        END;
        ROLLBACK TO value_test;
        IF NOT l_rejected THEN RAISE_APPLICATION_ERROR(-20002,'Invalid decimal value was accepted.'); END IF;
        DBMS_OUTPUT.PUT_LINE('Rejected invalid value: ' || NVL(TO_CHAR(p_value),'NULL'));
    END;
BEGIN
    SELECT MIN(TNO) INTO l_tno FROM MEASURINGUNIT;
    reject_value(NULL);
    reject_value(-1);
    reject_value(10);
    reject_value(1.5);
    FOR i IN 0..9 LOOP
        SAVEPOINT value_test;
        UPDATE MEASURINGUNIT SET DECIMALPLACE=i WHERE TNO=l_tno;
        ROLLBACK TO value_test;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('All integers 0 through 9 accepted. All test writes rolled back.');
END;
/
ROLLBACK;
